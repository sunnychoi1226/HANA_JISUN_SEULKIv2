create table if not exists public.hotel_verifications (
  hotel_key text primary key,
  hotel_name text not null,
  city text not null default '',
  country text not null default '',
  official_name text,
  star_rating numeric,
  total_rooms numeric,
  largest_event_capacity numeric,
  official_url text,
  group_sales_email text,
  address text,
  notes text,
  sources jsonb not null default '[]'::jsonb,
  verified_at timestamptz not null default now(),
  verified_by text
);
create index if not exists hotel_verifications_city_idx on public.hotel_verifications(city);
alter table public.hotel_verifications enable row level security;
