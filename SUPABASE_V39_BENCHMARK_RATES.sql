-- V39: 날짜·조건·출처가 있는 호텔 기준 공개가 이력
create table if not exists public.hotel_benchmark_rates (
  rate_id bigint generated by default as identity primary key,
  hotel_key text not null,
  hotel_name text not null,
  city text not null,
  currency text not null,
  rate_min numeric not null check (rate_min > 0),
  rate_max numeric not null check (rate_max >= rate_min),
  room_name text,
  stay_date date not null,
  checkout_date date not null,
  adults smallint not null default 2 check (adults > 0),
  children smallint not null default 0 check (children >= 0),
  rooms smallint not null default 1 check (rooms > 0),
  meal_plan text not null default 'room_only',
  tax_included boolean,
  source_name text not null,
  source_url text,
  searched_at timestamptz not null default now(),
  created_by text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint hotel_benchmark_rates_stay_check check (checkout_date > stay_date),
  constraint hotel_benchmark_rates_unique_observation unique (hotel_key, stay_date, source_name)
);

-- 이미 V39 테이블을 생성한 환경에도 객실명 컬럼을 안전하게 추가한다.
alter table public.hotel_benchmark_rates
  add column if not exists room_name text;

create index if not exists hotel_benchmark_rates_city_searched_idx
  on public.hotel_benchmark_rates(city, searched_at desc);
create index if not exists hotel_benchmark_rates_key_searched_idx
  on public.hotel_benchmark_rates(hotel_key, searched_at desc);

alter table public.hotel_benchmark_rates enable row level security;

